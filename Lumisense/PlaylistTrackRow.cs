namespace AudioPlayer;

/// <summary>
/// Одна строка трека в ЕДИНОМ, плоском, виртуализируемом списке — как для обычного плейлиста
/// (группировка по Folder через WPF GroupStyle, см. MainWindow.xaml), так и для отдельного
/// виртуального плейлиста "Избранное" (там группировки нет, но Folder всё равно указывает на
/// _favoritesFolder — единообразия ради, чтобы TrackItemTemplate не пришлось дублировать).
///
/// До этого класса каждая папка плейлиста рендерилась СВОИМ СОБСТВЕННЫМ вложенным ListView
/// (см. историю MainWindow.xaml), и то, к какой папке принадлежит трек, бралось из
/// унаследованного DataContext охватывающего ListView. У такой схемы виртуализация списка
/// была принципиально невозможна: вложенные ListView жили внутри ОДНОГО общего скролла
/// (свой ScrollViewer был отключён), а значит вынуждены были заранее реализовать (создать
/// визуальные контейнеры) КАЖДУЮ строку целиком, а не только видимые — на 1000+ треках это
/// был главный источник заметной задержки при каждом запуске.
///
/// Теперь и путь к файлу, и папка, к которой он принадлежит, — это два отдельных свойства
/// ОДНОГО объекта-строки, независимые от того, где эта строка физически лежит в визуальном
/// дереве. Это позволяет:
///  - использовать ОДИН настоящий виртуализирующий ListView на весь плейлист (с группировкой
///    по Folder для заголовков папок) — реализуются визуальные контейнеры только для реально
///    видимых строк, а не для всех сразу;
///  - обработчикам контекстного меню и т.п. брать оба значения прямо из унаследованного
///    DataContext (обычный Binding, без Tag/PlacementTarget/RelativeSource-трюков, которые
///    раньше были нужны только чтобы дотянуться до DataContext охватывающего ListView).
public sealed class PlaylistTrackRow
{
    public required PlaylistFolder Folder { get; init; }
    public required string FilePath { get; init; }

    // 1-based номер трека В ПРЕДЕЛАХ его папки — раньше вычислялся на лету через
    // TrackNumberFromListConverter (AlternationIndex/позиция в ItemsSource охватывающего
    // ListView), что имело смысл только пока у каждой папки был СВОЙ ListView. Теперь, когда
    // список один на всех, позиция трека в общем списке уже не совпадает с его позицией
    // внутри своей папки — просто считаем и сохраняем её явно при построении списка строк.
    public required int IndexInFolder { get; init; }
}
